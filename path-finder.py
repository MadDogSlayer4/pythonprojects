def print_maze(maze, stdscr, path=[]):
    red = curses.color_pair(1)
    blue = curses.color_pair(2)

    for i, row in enumerate(maze): # Gets index and value of row
        for j, value in enumerate(row): # gets index and value of row inside the list #i is row, j is column
            if (i, j) in path:
                stdscr.addstr(i, j*2, "X", red)
            else:
                stdscr.addstr(i, j*2, value, blue)

def find_path(maze, stdscr):
    start = "O"
    end = "X"
    start_pos = find_start(maze, start)

    q = queue.Queue()
    q.put((start_pos, [start_pos])) #inserts into queue

    visited = set()

    while not q.empty():
        current_pos, path = q.get() # gets the items at the front of the queue
        row, col = current_pos
    
        stdscr.clear()
        print_maze(maze, stdscr, path)
        stdscr.refresh()

        if maze[row][col] == end:
            return path
        
        neighbors = find_neighbors(maze, row, col)
        for neighbor in neighbors:
            if neighbor in visited:
                continue
            
            r, c = neighbor
            if maze[r][c] == "#":
                continue
            
            new_path = path + [neighbor]
            q.put((neighbor, new_path))
            visited.add(neighbor)
    return None
        
def find_neighbors(maze, row, col):
    neighbors = []

    if row > 0: # UP
        neighbors.append((row - 1, col))
    if row +1 < len(maze): # DOWN
        neighbors.append((row + 1, col))
    if col > 0: # LEFT
        neighbors.append((row, col - 1))
    if col + 1 < len(maze[0]): # RIGHT
        neighbors.append((row, col + 1))

    return neighbors

def find_start(maze, start):
    for i, row in enumerate(maze): # Gets index and value of row
        for j, value in enumerate(row):
            if value == start:
                return i, j
    return None

def main(stdscr):
    curses.init_pair(1, curses.COLOR_BLUE, curses.COLOR_BLACK)
